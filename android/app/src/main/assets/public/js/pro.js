/* ===== pro.js — Pro subscription & license activation (works 100% offline) =====
   Model: 30 EGP/month or 200 EGP/year, first 30 days free trial.
   User pays via Vodafone Cash → receives a code (DISPM- = monthly, DISPY- = yearly)
   → activates in-app. Codes generated by tools/make-codes.js → js/pro-codes.js. */
'use strict';

const PRO_KEY_XOR = 0x5A;
const TRIAL_DAYS = 30;
/* seller contact baked into the app so every customer sees it */
const PRO_SELLER_DEFAULT = { vf: '01030468736', wa: '01030468736' };

let PRO_STATE = { codeType: null, exp: 0, trialStart: 0 };

function proDeobf(b64) {
  try {
    const raw = atob(b64);
    let out = '';
    for (let i = 0; i < raw.length; i++) out += String.fromCharCode(raw.charCodeAt(i) ^ PRO_KEY_XOR);
    return out;
  } catch (e) { return ''; }
}
function proValidCodes() {
  const src = (typeof PRO_CODES !== 'undefined') ? PRO_CODES : { m: [], y: [] };
  return {
    m: (src.m || []).map(proDeobf),
    y: (src.y || []).map(proDeobf)
  };
}

/* ---------- state ---------- */
async function initPro() {
  PRO_STATE = (await kvGet('proState', null)) || { codeType: null, exp: 0, trialStart: 0 };
  /* migration: old one-time key */
  const old = await kvGet('proKey', '');
  if (old) {
    if (proValidCodes().m.includes(old.toUpperCase().trim()) || proValidCodes().y.includes(old.toUpperCase().trim())) {
      PRO_STATE.exp = Date.now() + 366 * 86400000;
      PRO_STATE.codeType = 'year';
      await kvSet('proState', PRO_STATE);
    }
    await kvSet('proKey', '');
  }
}

function isPro() {
  const now = Date.now();
  if ((+PRO_STATE.exp || 0) > now) return true;
  if (PRO_STATE.trialStart && now - PRO_STATE.trialStart < TRIAL_DAYS * 86400000) return true;
  return false;
}

function proDaysLeft() {
  if (!isPro()) return null;
  const now = Date.now();
  const end = Math.max(+PRO_STATE.exp || 0, PRO_STATE.trialStart ? PRO_STATE.trialStart + TRIAL_DAYS * 86400000 : 0);
  return Math.max(1, Math.ceil((end - now) / 86400000));
}

function proKindLabel() {
  if ((+PRO_STATE.exp || 0) > Date.now()) return PRO_STATE.codeType === 'year' ? '💎 اشتراك سنوي' : '💎 اشتراك شهري';
  return '🎁 تجربة مجانية';
}

/* call inside button handlers: if (!requirePro('...')) return; */
function requirePro(feature) {
  if (isPro()) return true;
  upgradeModal(feature || '');
  return false;
}

/* ---------- trial ---------- */
async function startTrial() {
  if (isPro()) return false;
  if (PRO_STATE.trialStart) {
    toast('استخدمت التجربة المجانية من قبل من هذا الجهاز 🙏');
    return false;
  }
  PRO_STATE.trialStart = Date.now();
  await kvSet('proState', PRO_STATE);
  toast('🎁 بدأت تجربتك المجانية — 30 يوم كامل بكل الميزات! استمتع', { duration: 6000 });
  if (window._renderProChip) window._renderProChip();
  return true;
}

/* ---------- activation ---------- */
async function activatePro(code) {
  const c = (code || '').toUpperCase().trim();
  if (!c) { toast('أدخل كود التفعيل'); return false; }
  const V = proValidCodes();
  const isMonth = V.m.includes(c);
  const isYear = V.y.includes(c);
  if (!isMonth && !isYear) { toast('❌ الكود غير صحيح — راجعه مع البائع'); return false; }
  /* extend from current expiry if still active (codes stack) */
  const base = Math.max(Date.now(), +PRO_STATE.exp || 0);
  PRO_STATE.exp = base + (isYear ? 366 : 31) * 86400000;
  PRO_STATE.codeType = isYear ? 'year' : 'month';
  await kvSet('proState', PRO_STATE);
  toast('💎 تم تفعيل ' + (isYear ? 'الاشتراك السنوي' : 'الاشتراك الشهري') + ' — شكرًا لدعمك!', { duration: 5000 });
  if (window._renderProChip) window._renderProChip();
  return true;
}

