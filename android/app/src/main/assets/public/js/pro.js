/* ---------- upgrade / buy screen ---------- */
function upgradeModal(feature) {
  getSellerInfo().then(si => {
    const vf = si.vf || PRO_SELLER_DEFAULT.vf;
    const wa = si.wa || PRO_SELLER_DEFAULT.wa;
    const priceLine = si.price
      ? '<div class="kv"><span class="k">💰 السعر</span><span class="v">' + esc(si.price) + '</span></div>'
      : '<div class="kv"><span class="k">🗓️ شهري</span><span class="v">30 ج.م</span></div>' +
        '<div class="kv"><span class="k">📅 سنوي</span><span class="v res-t">200 ج.م <span class="small">(توفّر 160 ج.م)</span></span></div>';

    const trialBtn = (!isPro() && !PRO_STATE.trialStart)
      ? '<div class="divider"></div>' +
        '<button class="btn btn-pos btn-block" id="up-trial">🎁 ابدأ أول 30 يوم مجانًا</button>' +
        '<div class="t2" style="margin:6px 0;text-align:center">جرّب كل الميزات مجانًا شهر كامل — بدون دفع وبدون كود</div>'
      : '';

    const statusLine = isPro()
      ? '<div class="kv"><span class="k">حالتك</span><span class="badge green">' + proKindLabel() +
        ' — متبقي <bdi dir="ltr">' + proDaysLeft() + '</bdi> يوم</span></div>' +
        '<div class="t2" style="margin-bottom:6px">عند انتهاء اشتراكك، فعّل كودًا جديدًا والوقت المتبقي يُجمع (مش بيضيع)</div>'
      : '';

    openModal(
      '<div class="modal-title">💎 النسخة الكاملة (Pro)</div>' +
      statusLine +
      '<div class="t2" style="margin-bottom:8px">كل الأساسيات مجانية للأبد' +
      (feature ? ' — <b>' + esc(feature) + '</b> من ميزات Pro' : '') + ':</div>' +
      proBenefits().map(b => '<div class="kv"><span class="v" style="text-align:right;font-weight:600">' + b + '</span></div>').join('') +
      '<div class="divider"></div>' +
      priceLine +
      trialBtn +
      '<div class="formula" style="margin-top:10px;line-height:2">' +
      '1️⃣ ادفع <b>30 ج.م</b> (شهري) أو <b>200 ج.م</b> (سنوي) عبر <b>فودافون كاش</b>:<br>' +
      '     <b><bdi dir="ltr">' + esc(vf) + '</b></b><br>' +
      '2️⃣ ابعت صورة الإيصال واتساب: <b><bdi dir="ltr">' + esc(wa) + '</b></b><br>' +
      '3️⃣ هتستلم كود (شهري أو سنوي) — أدخله هنا وتمتع فورًا' +
      '</div>' +
      '<div class="field" style="margin-top:10px"><label>كود التفعيل</label>' +
      '<input class="input input-lg" id="up-code" placeholder="DISPM-XXXX-XXXX أو DISPY-XXXX-XXXX" style="text-align:center" dir="ltr"></div>' +
      '<div class="modal-actions">' +
      '<button class="btn" onclick="closeModal()">لاحقًا</button>' +
      '<button class="btn btn-pos" id="up-activate">💎 تفعيل</button></div>',
      { onMount: w => {
        w.querySelector('#up-activate').onclick = async () => {
          const ok = await activatePro(w.querySelector('#up-code').value);
          if (ok) { closeModal(); go(Nav.current || 'home'); }
        };
        const tb = w.querySelector('#up-trial');
        if (tb) tb.onclick = async () => {
          const ok = await startTrial();
          if (ok) { closeModal(); go(Nav.current || 'home'); }
        };
      } }
    );
  });
}

/* status line used in Settings */
function proStatusLine() {
  const d = proDaysLeft();
  if (d === null) return '<div class="kv"><span class="k">الحالة</span><span class="badge gray">نسخة مجانية</span></div>';
  return '<div class="kv"><span class="k">الحالة</span><span class="badge green">' + proKindLabel() +
    ' — متبقي <bdi dir="ltr">' + d + '</bdi> يوم</span></div>';
}

